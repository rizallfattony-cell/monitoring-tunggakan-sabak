-- Rekap pembayaran premium bulanan untuk admin SIMONTOK.
-- Jalankan sekali di Supabase SQL Editor setelah step 17.

create table if not exists public.monitoring_premium_payments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  billing_month date not null,
  package_code text not null check (package_code in ('P1', 'P2', 'P3')),
  amount bigint not null check (amount >= 0),
  paid_at date,
  payment_note text,
  marked_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint monitoring_premium_payments_month_start_check
    check (billing_month = date_trunc('month', billing_month)::date),
  constraint monitoring_premium_payments_user_month_key unique (user_id, billing_month)
);

create index if not exists monitoring_premium_payments_month_idx
  on public.monitoring_premium_payments (billing_month desc, paid_at, user_id);

alter table public.monitoring_premium_payments enable row level security;

drop policy if exists "admin can view premium payments" on public.monitoring_premium_payments;
create policy "admin can view premium payments"
on public.monitoring_premium_payments
for select
to authenticated
using (
  exists (
    select 1
    from public.monitoring_profiles admin_profile
    where admin_profile.user_id = auth.uid()
      and admin_profile.role = 'admin'
  )
);

grant select on public.monitoring_premium_payments to authenticated;

create or replace function public.admin_list_premium_payments(p_billing_month date)
returns table (
  user_id uuid,
  username text,
  petugas text,
  package_code text,
  amount bigint,
  billing_month date,
  due_start date,
  due_end date,
  paid_at date,
  payment_note text,
  payment_status text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  month_start date := date_trunc('month', coalesce(p_billing_month, current_date))::date;
  month_end date := (date_trunc('month', coalesce(p_billing_month, current_date)) + interval '1 month - 1 day')::date;
begin
  if not exists (
    select 1
    from public.monitoring_profiles admin_profile
    where admin_profile.user_id = auth.uid()
      and admin_profile.role = 'admin'
  ) then
    raise exception 'Hanya admin yang dapat melihat rekap pembayaran premium';
  end if;

  insert into public.monitoring_premium_payments (
    user_id, billing_month, package_code, amount
  )
  select
    profile.user_id,
    month_start,
    profile.premium_package,
    case profile.premium_package
      when 'P1' then 15000
      when 'P2' then 25000
      when 'P3' then 50000
    end
  from public.monitoring_profiles profile
  where profile.role <> 'admin'
    and profile.premium_package in ('P1', 'P2', 'P3')
    and month_start = date_trunc('month', current_date)::date
  on conflict (user_id, billing_month) do nothing;

  return query
  select
    payment.user_id,
    upper(split_part(profile.email, '@', 1)) as username,
    coalesce(nullif(profile.petugas, ''), upper(split_part(profile.email, '@', 1))) as petugas,
    payment.package_code,
    payment.amount,
    payment.billing_month,
    (month_start + 19) as due_start,
    month_end as due_end,
    payment.paid_at,
    payment.payment_note,
    case
      when payment.paid_at is not null then 'paid'
      when current_date > month_end then 'overdue'
      else 'unpaid'
    end as payment_status
  from public.monitoring_premium_payments payment
  join public.monitoring_profiles profile on profile.user_id = payment.user_id
  where payment.billing_month = month_start
  order by
    case when payment.paid_at is null then 0 else 1 end,
    coalesce(nullif(profile.petugas, ''), profile.email);
end;
$$;

create or replace function public.admin_set_premium_payment(
  p_user_id uuid,
  p_billing_month date,
  p_paid_at date,
  p_note text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  month_start date := date_trunc('month', coalesce(p_billing_month, current_date))::date;
  month_end date := (date_trunc('month', coalesce(p_billing_month, current_date)) + interval '1 month - 1 day')::date;
  package_value text;
  amount_value bigint;
begin
  if not exists (
    select 1
    from public.monitoring_profiles admin_profile
    where admin_profile.user_id = auth.uid()
      and admin_profile.role = 'admin'
  ) then
    raise exception 'Hanya admin yang dapat mengubah pembayaran premium';
  end if;

  if p_paid_at is not null and (p_paid_at < month_start + 19 or p_paid_at > month_end) then
    raise exception 'Tanggal pembayaran harus berada antara tanggal 20 dan akhir bulan';
  end if;

  select payment.package_code, payment.amount
    into package_value, amount_value
  from public.monitoring_premium_payments payment
  where payment.user_id = p_user_id
    and payment.billing_month = month_start;

  if not found then
    select profile.premium_package,
           case profile.premium_package when 'P1' then 15000 when 'P2' then 25000 when 'P3' then 50000 end
      into package_value, amount_value
    from public.monitoring_profiles profile
    where profile.user_id = p_user_id
      and profile.role <> 'admin';
  end if;

  if package_value is null or package_value not in ('P1', 'P2', 'P3') then
    raise exception 'Pengguna tidak memiliki paket premium yang dapat ditagihkan';
  end if;

  insert into public.monitoring_premium_payments (
    user_id, billing_month, package_code, amount, paid_at, payment_note, marked_by, updated_at
  ) values (
    p_user_id, month_start, package_value, amount_value, p_paid_at,
    nullif(trim(coalesce(p_note, '')), ''),
    case when p_paid_at is null then null else auth.uid() end,
    now()
  )
  on conflict (user_id, billing_month) do update
  set paid_at = excluded.paid_at,
      payment_note = excluded.payment_note,
      marked_by = excluded.marked_by,
      updated_at = now();
end;
$$;

revoke all on function public.admin_list_premium_payments(date) from public;
revoke all on function public.admin_set_premium_payment(uuid, date, date, text) from public;

grant execute on function public.admin_list_premium_payments(date) to authenticated;
grant execute on function public.admin_set_premium_payment(uuid, date, date, text) to authenticated;
