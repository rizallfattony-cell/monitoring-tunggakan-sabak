-- Premium is assigned directly by an administrator after receiving proof manually.
-- The legacy monitoring_premium_requests table is intentionally kept for history,
-- but the web admin no longer depends on payment-proof uploads.

alter table public.monitoring_profiles
  add column if not exists premium_active_from date,
  add column if not exists premium_admin_note text,
  add column if not exists premium_updated_by uuid references auth.users(id);

create table if not exists public.monitoring_premium_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  action text not null check (action in ('activated', 'updated', 'disabled', 'device_reset')),
  package_code text,
  active_from date,
  active_until date,
  admin_note text,
  changed_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);

create index if not exists monitoring_premium_history_user_created_idx
  on public.monitoring_premium_history (user_id, created_at desc);

alter table public.monitoring_premium_history enable row level security;

drop policy if exists "admin can view premium history" on public.monitoring_premium_history;
create policy "admin can view premium history"
on public.monitoring_premium_history
for select
to authenticated
using (
  exists (
    select 1
    from public.monitoring_profiles admin_profile
    where admin_profile.user_id = auth.uid()
      and admin_profile.role = 'admin'
  )
);

grant select on public.monitoring_premium_history to authenticated;

create or replace function public.admin_list_premium_users()
returns table (
  user_id uuid,
  username text,
  petugas text,
  email text,
  role text,
  premium_package text,
  premium_active_from date,
  premium_active_until date,
  premium_admin_note text,
  premium_device_id text,
  premium_updated_at timestamptz,
  days_remaining integer
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1
    from public.monitoring_profiles admin_profile
    where admin_profile.user_id = auth.uid()
      and admin_profile.role = 'admin'
  ) then
    raise exception 'Hanya admin yang dapat mengelola premium';
  end if;

  return query
  select
    profile.user_id,
    upper(split_part(profile.email, '@', 1)) as username,
    coalesce(nullif(profile.petugas, ''), upper(split_part(profile.email, '@', 1))) as petugas,
    profile.email,
    profile.role,
    profile.premium_package,
    profile.premium_active_from,
    profile.premium_active_until,
    profile.premium_admin_note,
    profile.premium_device_id,
    profile.premium_updated_at,
    case
      when profile.premium_active_until is null then null
      else (profile.premium_active_until - current_date)::integer
    end as days_remaining
  from public.monitoring_profiles profile
  where profile.role <> 'admin'
  order by
    case
      when profile.premium_package <> 'FREE'
       and profile.premium_active_until >= current_date then 0
      when profile.premium_package <> 'FREE' then 1
      else 2
    end,
    profile.premium_active_until asc nulls last,
    coalesce(nullif(profile.petugas, ''), profile.email);
end;
$$;

create or replace function public.admin_set_premium_access(
  p_user_id uuid,
  p_package text,
  p_active_from date,
  p_active_until date,
  p_note text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  previous_package text;
  previous_until date;
begin
  if not exists (
    select 1
    from public.monitoring_profiles admin_profile
    where admin_profile.user_id = auth.uid()
      and admin_profile.role = 'admin'
  ) then
    raise exception 'Hanya admin yang dapat mengelola premium';
  end if;

  if p_package not in ('P1', 'P2', 'P3') then
    raise exception 'Paket premium tidak valid';
  end if;

  if p_active_from is null or p_active_until is null or p_active_until < p_active_from then
    raise exception 'Periode premium tidak valid';
  end if;

  select profile.premium_package, profile.premium_active_until
    into previous_package, previous_until
  from public.monitoring_profiles profile
  where profile.user_id = p_user_id
    and profile.role <> 'admin'
  for update;

  if not found then
    raise exception 'Pengguna premium tidak ditemukan';
  end if;

  update public.monitoring_profiles
  set premium_package = p_package,
      premium_active_from = p_active_from,
      premium_active_until = p_active_until,
      premium_admin_note = nullif(trim(coalesce(p_note, '')), ''),
      premium_updated_by = auth.uid(),
      premium_updated_at = now()
  where user_id = p_user_id;

  insert into public.monitoring_premium_history (
    user_id, action, package_code, active_from, active_until, admin_note, changed_by
  ) values (
    p_user_id,
    case when previous_package is null or previous_until is null then 'activated' else 'updated' end,
    p_package,
    p_active_from,
    p_active_until,
    nullif(trim(coalesce(p_note, '')), ''),
    auth.uid()
  );
end;
$$;

create or replace function public.admin_disable_premium_access(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  old_package text;
  old_from date;
  old_until date;
begin
  if not exists (
    select 1 from public.monitoring_profiles
    where user_id = auth.uid() and role = 'admin'
  ) then
    raise exception 'Hanya admin yang dapat mengelola premium';
  end if;

  select premium_package, premium_active_from, premium_active_until
    into old_package, old_from, old_until
  from public.monitoring_profiles
  where user_id = p_user_id and role <> 'admin'
  for update;

  if not found then raise exception 'Pengguna premium tidak ditemukan'; end if;

  update public.monitoring_profiles
  set premium_package = 'FREE',
      premium_active_from = null,
      premium_active_until = null,
      premium_admin_note = null,
      premium_device_id = null,
      premium_device_bound_at = null,
      premium_updated_by = auth.uid(),
      premium_updated_at = now()
  where user_id = p_user_id;

  insert into public.monitoring_premium_history (
    user_id, action, package_code, active_from, active_until, changed_by
  ) values (p_user_id, 'disabled', old_package, old_from, old_until, auth.uid());
end;
$$;

create or replace function public.admin_reset_premium_device(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1 from public.monitoring_profiles
    where user_id = auth.uid() and role = 'admin'
  ) then
    raise exception 'Hanya admin yang dapat mengelola premium';
  end if;

  update public.monitoring_profiles
  set premium_device_id = null,
      premium_device_bound_at = null,
      premium_updated_by = auth.uid(),
      premium_updated_at = now()
  where user_id = p_user_id and role <> 'admin';

  if not found then raise exception 'Pengguna premium tidak ditemukan'; end if;

  insert into public.monitoring_premium_history (
    user_id, action, package_code, active_from, active_until, admin_note, changed_by
  )
  select user_id, 'device_reset', premium_package, premium_active_from,
         premium_active_until, 'Perangkat premium direset admin', auth.uid()
  from public.monitoring_profiles
  where user_id = p_user_id;
end;
$$;

